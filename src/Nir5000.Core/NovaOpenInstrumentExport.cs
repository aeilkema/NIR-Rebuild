using System.Text.Json;
using System.Text.Json.Serialization;

namespace Nir5000.Core;

public sealed record NovaSampleExport(
    [property: JsonPropertyName("analysisStart")] DateTime AnalysisStart,
    [property: JsonPropertyName("analysisEnd")] DateTime AnalysisEnd,
    [property: JsonPropertyName("comment")] string Comment,
    [property: JsonPropertyName("productName")] string ProductName,
    [property: JsonPropertyName("productCode")] string ProductCode,
    [property: JsonPropertyName("sampleNumber")] string SampleNumber,
    [property: JsonPropertyName("absScans")] IReadOnlyList<NovaAbsScanExport> AbsScans);

public sealed record NovaAbsScanExport(
    [property: JsonPropertyName("identification")] string Identification,
    [property: JsonPropertyName("timestamp")] DateTime Timestamp,
    [property: JsonPropertyName("segments")] IReadOnlyList<NovaSegmentExport> Segments);

public sealed record NovaSegmentExport(
    [property: JsonPropertyName("unit")] string Unit,
    [property: JsonPropertyName("start")] double Start,
    [property: JsonPropertyName("end")] double End,
    [property: JsonPropertyName("usedStart")] double UsedStart,
    [property: JsonPropertyName("usedEnd")] double UsedEnd,
    [property: JsonPropertyName("step")] double Step,
    [property: JsonPropertyName("values")] IReadOnlyList<double> Values);

/// <summary>
/// Creates the neutral payload shape observed in Nova's official
/// Foss.Api.OpenInstrument.Client model. It does not contact Nova or emulate
/// an instrument identity; submission remains an explicit host integration.
/// </summary>
public static class NovaOpenInstrumentExport
{
    public static NovaSampleExport Create(Spectrum spectrum, string sampleNumber = "NIR-Rebuild-replay", string productName = "NIR 5000 replay", string productCode = "NIR5000")
    {
        if (spectrum.WavelengthsNm.Count != spectrum.Values.Count || spectrum.Values.Count < 2)
            throw new InvalidDataException("A spectrum must contain matching wavelength/value arrays with at least two points.");
        var start = spectrum.WavelengthsNm[0];
        var end = spectrum.WavelengthsNm[^1];
        var step = spectrum.WavelengthsNm[1] - spectrum.WavelengthsNm[0];
        if (!double.IsFinite(start) || !double.IsFinite(end) || !double.IsFinite(step) || step <= 0)
            throw new InvalidDataException("The spectrum wavelength axis is invalid for a Nova segment.");
        var timestamp = spectrum.CapturedAt == DateTimeOffset.MinValue ? DateTime.UtcNow : spectrum.CapturedAt.UtcDateTime;
        var segment = new NovaSegmentExport("nm", start, end, start, end, step, spectrum.Values.ToArray());
        var scan = new NovaAbsScanExport("NIR-Rebuild NIR5000 replay", timestamp, [segment]);
        return new NovaSampleExport(timestamp, timestamp, "Generated by NIR-Rebuild; replay/simulator provenance.", productName, productCode, sampleNumber, [scan]);
    }

    public static void WriteJson(string path, NovaSampleExport sample)
    {
        var options = new JsonSerializerOptions { WriteIndented = true, DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull };
        File.WriteAllText(path, JsonSerializer.Serialize(sample, options));
    }
}
